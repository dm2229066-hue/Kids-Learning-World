export function playAnimalTone(pitch: 'low' | 'mid' | 'chirp', enabled = true) {
  if (!enabled) return;
  const ctx = getAudioContext();
  if (!ctx) return;
  try {
    const now = ctx.currentTime;
    if (pitch === 'chirp') {
      [0, 0.12].forEach((offset) => {
        const osc = ctx.createOscillator();
        const gain = ctx.createGain();
        osc.type = 'sine';
        osc.frequency.setValueAtTime(1100, now + offset);
        osc.frequency.exponentialRampToValueAtTime(1650, now + offset + 0.07);
        gain.gain.setValueAtTime(0.12, now + offset);
        gain.gain.exponentialRampToValueAtTime(0.001, now + offset + 0.09);
        osc.connect(gain);
        gain.connect(ctx.destination);
        osc.start(now + offset);
        osc.stop(now + offset + 0.1);
      });
    } else if (pitch === 'low') {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = 'sawtooth';
      osc.frequency.setValueAtTime(160, now);
      osc.frequency.exponentialRampToValueAtTime(105, now + 0.28);
      gain.gain.setValueAtTime(0.08, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.3);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start(now);
      osc.stop(now + 0.32);
    } else {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();
      osc.type = 'triangle';
      osc.frequency.setValueAtTime(340, now);
      osc.frequency.exponentialRampToValueAtTime(460, now + 0.14);
      gain.gain.setValueAtTime(0.14, now);
      gain.gain.exponentialRampToValueAtTime(0.001, now + 0.18);
      osc.connect(gain);
      gain.connect(ctx.destination);
      osc.start(now);
      osc.stop(now + 0.2);
    }
  } catch {
    // Ignore audio context restrictions
  }
}

export function speakText(
  text: string,
  lang: Language = 'en',
  enabled = true,
  rate = 0.9
) {
  if (!enabled || typeof window === 'undefined' || !('speechSynthesis' in window)) {
    return;
  }
  try {
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(text);
    const targetLang = lang === 'hi' ? 'hi-IN' : 'en-US';
    utterance.lang = targetLang;
    utterance.rate = rate;
    utterance.pitch = 1.1;

    const voices = window.speechSynthesis.getVoices();
    if (voices.length > 0) {
      const exactMatch = voices.find((v) => v.lang.toLowerCase() === targetLang.toLowerCase());
      const prefixMatch = voices.find((v) =>
        v.lang.toLowerCase().startsWith(lang === 'hi' ? 'hi' : 'en')
      );
      if (exactMatch) {
        utterance.voice = exactMatch;
      } else if (prefixMatch) {
        utterance.voice = prefixMatch;
      }
    }
    window.speechSynthesis.speak(utterance);
  } catch {
    // Ignore speech synthesis errors
  }
}
